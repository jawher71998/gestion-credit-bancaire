<main class="auth-page">
  <div class="wrap" style="max-width: 760px;">
    <h1>À propos de ce projet</h1>
    <p class="auth-lede">
      Cette plateforme a été conçue dans le cadre d'un Projet de Fin d'Études
      (BTS Informatique de Gestion), en s'inspirant du fonctionnement réel
      d'une agence bancaire tunisienne.
    </p>

    <div class="admin-table-wrap" style="margin-top:24px;">
      <h2>L'objectif</h2>
      <p>
        Digitaliser le traitement des demandes de crédit : simulation en ligne,
        dépôt de dossier avec pièces justificatives, étude par un agent puis,
        selon le montant, validation finale par un chef d'agence, et génération
        automatique de l'échéancier de remboursement.
      </p>
    </div>

    <div class="admin-table-wrap" style="margin-top:20px;">
      <h2>Les produits de financement</h2>
      <p>
        Le site propose un crédit consommation classique ainsi que deux
        formules conformes à la finance islamique : le <strong>Mourabaha</strong>
        (financement immobilier) et l'<strong>Ijara</strong> (crédit-bail automobile),
        pour refléter l'offre d'une banque comme Banque Zitouna.
      </p>
    </div>

    <div class="admin-table-wrap" style="margin-top:20px;">
      <h2>La technologie utilisée</h2>
      <p>
        HTML5, CSS3 et JavaScript pour l'interface, PHP natif pour le
        traitement côté serveur, et MySQL pour la base de données. Le projet
        n'utilise volontairement aucun framework, dans un but pédagogique de
        maîtrise des fondamentaux.
      </p>
    </div>
  </div>
